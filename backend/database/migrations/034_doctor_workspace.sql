
-- MedAxis: Doctor Workspace
-- The existing Node.js migration runner manages transactions.

CREATE TABLE IF NOT EXISTS doctor_workspace_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    doctor_user_id BIGINT NOT NULL REFERENCES users(id),
    patient_id BIGINT REFERENCES patients(id),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    priority VARCHAR(20) NOT NULL DEFAULT 'normal'
        CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'completed', 'cancelled')),
    due_at TIMESTAMPTZ,
    created_by BIGINT REFERENCES users(id),
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS doctor_clinical_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    doctor_user_id BIGINT NOT NULL REFERENCES users(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    note_type VARCHAR(30) NOT NULL DEFAULT 'progress'
        CHECK (note_type IN (
            'progress', 'consultation', 'follow_up',
            'discharge', 'other'
        )),
    subject VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    is_signed BOOLEAN NOT NULL DEFAULT FALSE,
    signed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_doctor_tasks_assigned
    ON doctor_workspace_tasks (hospital_id, doctor_user_id, status);

CREATE INDEX IF NOT EXISTS idx_doctor_tasks_due
    ON doctor_workspace_tasks (doctor_user_id, due_at);

CREATE INDEX IF NOT EXISTS idx_doctor_notes_patient
    ON doctor_clinical_notes (hospital_id, patient_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_doctor_notes_author
    ON doctor_clinical_notes (doctor_user_id, created_at DESC);

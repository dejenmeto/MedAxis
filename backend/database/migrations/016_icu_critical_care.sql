CREATE TABLE IF NOT EXISTS icu_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    department_id BIGINT REFERENCES departments(id),
    unit_code VARCHAR(50) NOT NULL,
    unit_name VARCHAR(150) NOT NULL,
    unit_type VARCHAR(30) NOT NULL DEFAULT 'general'
        CHECK (unit_type IN (
            'general', 'adult', 'pediatric', 'neonatal', 'cardiac'
        )),
    floor_number VARCHAR(30),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, unit_code)
);

CREATE TABLE IF NOT EXISTS icu_beds (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    unit_id BIGINT NOT NULL REFERENCES icu_units(id),
    bed_code VARCHAR(50) NOT NULL,
    bed_status VARCHAR(25) NOT NULL DEFAULT 'available'
        CHECK (bed_status IN (
            'available', 'occupied', 'maintenance', 'reserved', 'isolation'
        )),
    monitoring_level VARCHAR(30) NOT NULL DEFAULT 'standard'
        CHECK (monitoring_level IN (
            'standard', 'continuous', 'advanced'
        )),
    equipment_notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, bed_code),
    UNIQUE (id, hospital_id)
);

CREATE TABLE IF NOT EXISTS icu_stays (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    admission_id UUID REFERENCES admissions(id),
    bed_id UUID NOT NULL REFERENCES icu_beds(id),
    attending_staff_id BIGINT REFERENCES staff_profiles(id),
    admitted_by BIGINT REFERENCES users(id),
    stay_number VARCHAR(60) NOT NULL,
    admission_reason TEXT NOT NULL,
    admission_diagnosis TEXT,
    clinical_summary TEXT,
    admitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    discharged_at TIMESTAMPTZ,
    discharge_summary TEXT,
    stay_status VARCHAR(25) NOT NULL DEFAULT 'active'
        CHECK (stay_status IN (
            'active', 'discharged', 'transferred', 'cancelled'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, stay_number),
    CHECK (
        discharged_at IS NULL OR discharged_at >= admitted_at
    ),
    FOREIGN KEY (bed_id, hospital_id)
        REFERENCES icu_beds(id, hospital_id)
);


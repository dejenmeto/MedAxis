-- Creates in-app notifications for individual users.
-- The existing migrate.js runner manages the transaction.

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    hospital_id BIGINT NULL
        REFERENCES hospitals(id) ON DELETE CASCADE,

    recipient_user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    created_by BIGINT NULL
        REFERENCES users(id) ON DELETE SET NULL,

    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,

    category VARCHAR(40) NOT NULL DEFAULT 'general'
        CHECK (
            category IN (
                'general',
                'appointment',
                'queue',
                'laboratory',
                'pharmacy',
                'billing',
                'emergency',
                'system'
            )
        ),

    priority VARCHAR(20) NOT NULL DEFAULT 'normal'
        CHECK (priority IN ('low', 'normal', 'high', 'urgent')),

    status VARCHAR(20) NOT NULL DEFAULT 'unread'
        CHECK (status IN ('unread', 'read', 'archived')),

    action_url VARCHAR(500) NULL,

    read_at TIMESTAMPTZ NULL,
    archived_at TIMESTAMPTZ NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notifications_recipient_created
    ON notifications (recipient_user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_recipient_status
    ON notifications (recipient_user_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_hospital_created
    ON notifications (hospital_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_category
    ON notifications (category);
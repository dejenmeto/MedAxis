
-- 023_queue_patient_flow.sql
-- Patient queue and service-flow management for MedAxis.
-- The existing migration runner manages the transaction.

CREATE TABLE IF NOT EXISTS patient_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    hospital_id BIGINT NOT NULL
        REFERENCES hospitals(id) ON DELETE CASCADE,

    patient_id BIGINT NOT NULL
        REFERENCES patients(id) ON DELETE RESTRICT,

    queue_date DATE NOT NULL DEFAULT CURRENT_DATE,
    queue_number INTEGER NOT NULL,
    queue_code VARCHAR(40) NOT NULL,

    department VARCHAR(120) NOT NULL,
    priority VARCHAR(20) NOT NULL DEFAULT 'normal',
    status VARCHAR(30) NOT NULL DEFAULT 'waiting',

    assigned_to BIGINT
        REFERENCES users(id) ON DELETE SET NULL,

    notes TEXT,

    called_at TIMESTAMPTZ,
    service_started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,

    created_by BIGINT
        REFERENCES users(id) ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT patient_queue_number_positive
        CHECK (queue_number > 0),

    CONSTRAINT patient_queue_priority_valid
        CHECK (priority IN ('low', 'normal', 'high', 'urgent')),

    CONSTRAINT patient_queue_status_valid
        CHECK (
            status IN (
                'waiting',
                'called',
                'in_service',
                'completed',
                'skipped',
                'cancelled'
            )
        ),

    CONSTRAINT patient_queue_hospital_date_number_unique
        UNIQUE (hospital_id, queue_date, queue_number),

    CONSTRAINT patient_queue_hospital_date_code_unique
        UNIQUE (hospital_id, queue_date, queue_code)
);

CREATE INDEX IF NOT EXISTS idx_patient_queue_hospital_date
    ON patient_queue (hospital_id, queue_date);

CREATE INDEX IF NOT EXISTS idx_patient_queue_status
    ON patient_queue (hospital_id, status, queue_date);

CREATE INDEX IF NOT EXISTS idx_patient_queue_patient
    ON patient_queue (patient_id);

CREATE INDEX IF NOT EXISTS idx_patient_queue_department
    ON patient_queue (hospital_id, department, queue_date);

CREATE INDEX IF NOT EXISTS idx_patient_queue_assigned_staff
    ON patient_queue (assigned_to);

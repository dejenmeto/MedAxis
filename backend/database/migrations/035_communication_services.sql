
CREATE TABLE IF NOT EXISTS communication_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    template_key VARCHAR(100) NOT NULL,
    channel VARCHAR(10) NOT NULL CHECK (channel IN ('email', 'sms')),
    subject VARCHAR(250),
    body TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, template_key, channel)
);

CREATE TABLE IF NOT EXISTS communication_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    channel VARCHAR(10) NOT NULL CHECK (channel IN ('email', 'sms')),
    recipient VARCHAR(320) NOT NULL,
    subject VARCHAR(250),
    body TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'sent', 'failed')),
    provider_message_id VARCHAR(250),
    error_message TEXT,
    attempts INTEGER NOT NULL DEFAULT 0,
    sent_by BIGINT REFERENCES users(id),
    sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_communication_logs_hospital
    ON communication_logs (hospital_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_communication_logs_status
    ON communication_logs (hospital_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_communication_templates_lookup
    ON communication_templates (hospital_id, channel, is_active);

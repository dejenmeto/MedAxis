
-- MedAxis: Telemedicine consultations
-- The existing migration runner manages the transaction.

CREATE TABLE IF NOT EXISTS telemedicine_consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),

    consultation_code VARCHAR(40) NOT NULL,
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    doctor_staff_id BIGINT NOT NULL REFERENCES staff_profiles(id),

    patient_name VARCHAR(200),
    doctor_name VARCHAR(200),

    consultation_mode VARCHAR(20) NOT NULL DEFAULT 'video'
        CHECK (consultation_mode IN ('video', 'phone')),

    scheduled_at TIMESTAMPTZ NOT NULL,
    duration_minutes INTEGER NOT NULL DEFAULT 30
        CHECK (duration_minutes BETWEEN 5 AND 240),

    status VARCHAR(20) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN (
            'scheduled',
            'confirmed',
            'in_progress',
            'completed',
            'cancelled'
        )),

    meeting_url TEXT,
    consultation_notes TEXT,
    follow_up_instructions TEXT,

    created_by BIGINT REFERENCES users(id),
    updated_by BIGINT REFERENCES users(id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_telemedicine_hospital_code
        UNIQUE (hospital_id, consultation_code)
);

CREATE INDEX IF NOT EXISTS idx_telemedicine_hospital_schedule
    ON telemedicine_consultations (hospital_id, scheduled_at DESC);

CREATE INDEX IF NOT EXISTS idx_telemedicine_hospital_status
    ON telemedicine_consultations (hospital_id, status);

CREATE INDEX IF NOT EXISTS idx_telemedicine_patient
    ON telemedicine_consultations (patient_id);

CREATE INDEX IF NOT EXISTS idx_telemedicine_doctor_schedule
    ON telemedicine_consultations (doctor_staff_id, scheduled_at DESC);

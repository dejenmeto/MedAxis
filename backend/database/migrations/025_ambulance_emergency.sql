
-- MedAxis: Ambulance Fleet and Emergency Dispatch
-- The migration runner manages BEGIN/COMMIT automatically.

CREATE TABLE IF NOT EXISTS ambulance_vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    vehicle_number VARCHAR(40) NOT NULL,
    vehicle_type VARCHAR(60) NOT NULL DEFAULT 'ambulance',
    capacity INTEGER NOT NULL DEFAULT 1 CHECK (capacity > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'dispatched', 'maintenance', 'inactive')),
    current_location VARCHAR(255),
    notes TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, vehicle_number)
);

CREATE TABLE IF NOT EXISTS ambulance_dispatches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    dispatch_code VARCHAR(40) NOT NULL,
    patient_id BIGINT REFERENCES patients(id) ON DELETE SET NULL,
    patient_name VARCHAR(160) NOT NULL,
    patient_phone VARCHAR(40),
    emergency_type VARCHAR(100) NOT NULL,
    priority VARCHAR(20) NOT NULL DEFAULT 'normal'
        CHECK (priority IN ('low', 'normal', 'high', 'critical')),
    pickup_location VARCHAR(255) NOT NULL,
    destination VARCHAR(255),
    vehicle_id BIGINT REFERENCES ambulance_vehicles(id) ON DELETE SET NULL,
    driver_name VARCHAR(160),
    assigned_team VARCHAR(255),
    status VARCHAR(25) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'dispatched', 'arrived',
            'transporting', 'completed', 'cancelled'
        )),
    call_received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    dispatched_at TIMESTAMPTZ,
    arrived_at TIMESTAMPTZ,
    transport_started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    notes TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, dispatch_code)
);

CREATE INDEX IF NOT EXISTS idx_ambulance_vehicles_hospital_status
    ON ambulance_vehicles (hospital_id, status);

CREATE INDEX IF NOT EXISTS idx_ambulance_dispatches_hospital_status
    ON ambulance_dispatches (hospital_id, status);

CREATE INDEX IF NOT EXISTS idx_ambulance_dispatches_hospital_date
    ON ambulance_dispatches (hospital_id, call_received_at DESC);

CREATE INDEX IF NOT EXISTS idx_ambulance_dispatches_patient
    ON ambulance_dispatches (patient_id);

-- 1. Inventory categories
CREATE TABLE IF NOT EXISTS inventory_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    name VARCHAR(120) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, name),
    UNIQUE (hospital_id, id)
);

-- 2. Suppliers
CREATE TABLE IF NOT EXISTS inventory_suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    supplier_code VARCHAR(60) NOT NULL,
    name VARCHAR(180) NOT NULL,
    contact_person VARCHAR(150),
    email VARCHAR(255),
    phone VARCHAR(50),
    address TEXT,
    tax_number VARCHAR(100),
    payment_terms VARCHAR(150),
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, supplier_code),
    UNIQUE (hospital_id, id)
);

-- 3. General inventory items
CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    category_id BIGINT,
    item_code VARCHAR(80) NOT NULL,
    name VARCHAR(180) NOT NULL,
    description TEXT,
    unit VARCHAR(40) NOT NULL DEFAULT 'piece',
    quantity_on_hand NUMERIC(14, 3) NOT NULL DEFAULT 0,
    reorder_level NUMERIC(14, 3) NOT NULL DEFAULT 0,
    unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0,
    storage_location VARCHAR(150),
    expiry_date DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT inventory_items_quantity_check
        CHECK (quantity_on_hand >= 0),
    CONSTRAINT inventory_items_reorder_check
        CHECK (reorder_level >= 0),
    CONSTRAINT inventory_items_cost_check
        CHECK (unit_cost >= 0),
    CONSTRAINT inventory_items_category_fk
        FOREIGN KEY (hospital_id, category_id)
        REFERENCES inventory_categories(hospital_id, id),
    UNIQUE (hospital_id, item_code),
    UNIQUE (hospital_id, id)
);

-- 4. Inventory movement ledger.

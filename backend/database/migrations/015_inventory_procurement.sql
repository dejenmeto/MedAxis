    expected_delivery_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'ETB',
    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    notes TEXT,
    created_by BIGINT,
    approved_by BIGINT,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT purchase_orders_status_check
        CHECK (
            status IN (
                'draft',
                'submitted',
                'approved',
                'ordered',
                'partially_received',
                'received',
                'cancelled'
            )
        ),
    CONSTRAINT purchase_orders_amounts_check
        CHECK (
            subtotal >= 0
            AND tax_amount >= 0
            AND total_amount >= 0
        ),
    CONSTRAINT purchase_orders_supplier_fk
        FOREIGN KEY (hospital_id, supplier_id)
        REFERENCES inventory_suppliers(hospital_id, id),
    UNIQUE (hospital_id, order_number),
    UNIQUE (hospital_id, id)
);

-- 6. Purchase order line items
CREATE TABLE IF NOT EXISTS purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL,
    purchase_order_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    quantity_ordered NUMERIC(14, 3) NOT NULL,
    quantity_received NUMERIC(14, 3) NOT NULL DEFAULT 0,
    unit_cost NUMERIC(14, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT purchase_order_items_quantity_check
        CHECK (
            quantity_ordered > 0
            AND quantity_received >= 0
            AND quantity_received <= quantity_ordered
        ),
    CONSTRAINT purchase_order_items_cost_check
        CHECK (unit_cost >= 0),
    CONSTRAINT purchase_order_items_order_fk
        FOREIGN KEY (hospital_id, purchase_order_id)

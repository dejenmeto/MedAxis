    reference_id BIGINT,
    notes TEXT,
    performed_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT inventory_stock_transaction_type_check
        CHECK (
            transaction_type IN (
                'opening_stock',
                'receipt',
                'issue',
                'adjustment_in',
                'adjustment_out',
                'return'
            )
        ),
    CONSTRAINT inventory_stock_transaction_quantity_check
        CHECK (quantity > 0),
    CONSTRAINT inventory_stock_transaction_cost_check
        CHECK (unit_cost >= 0),
    CONSTRAINT inventory_stock_transaction_item_fk
        FOREIGN KEY (hospital_id, item_id)
        REFERENCES inventory_items(hospital_id, id)
);

-- 5. Purchase orders
CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    order_number VARCHAR(80) NOT NULL,
    supplier_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'draft',

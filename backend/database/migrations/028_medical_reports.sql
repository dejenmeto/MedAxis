
CREATE TABLE IF NOT EXISTS medical_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    report_code VARCHAR(60) NOT NULL,
    report_type VARCHAR(60) NOT NULL,
    title VARCHAR(200) NOT NULL,
    clinical_history TEXT,
    findings TEXT NOT NULL,
    impression TEXT NOT NULL,
    recommendations TEXT,
    report_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'final')),
    prepared_by BIGINT REFERENCES users(id),
    finalized_at TIMESTAMPTZ,
    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_medical_reports_hospital_code
        UNIQUE (hospital_id, report_code)
);

CREATE INDEX IF NOT EXISTS idx_medical_reports_patient
    ON medical_reports (hospital_id, patient_id, report_date DESC);

CREATE INDEX IF NOT EXISTS idx_medical_reports_status
    ON medical_reports (hospital_id, status, is_archived, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_medical_reports_type
    ON medical_reports (hospital_id, report_type);

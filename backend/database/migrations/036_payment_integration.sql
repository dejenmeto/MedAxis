-- Payment transaction ledger for MedAxis.
-- The existing migrate.js runner handles transactions.

CREATE TABLE IF NOT EXISTS payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    invoice_id TEXT,
    transaction_reference VARCHAR(120) NOT NULL UNIQUE,
    provider VARCHAR(40) NOT NULL DEFAULT 'test',
    payment_method VARCHAR(40) NOT NULL DEFAULT 'other',
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'ETB',
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'success', 'failed', 'cancelled'
        )),
    payer_name VARCHAR(160),
    payer_email VARCHAR(255),
    payer_phone VARCHAR(40),
    provider_reference VARCHAR(255),
    checkout_url TEXT,
    failure_reason TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    initiated_by BIGINT REFERENCES users(id),
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_hospital
    ON payment_transactions (hospital_id);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_status
    ON payment_transactions (hospital_id, status);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_invoice
    ON payment_transactions (invoice_id);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_created
    ON payment_transactions (created_at DESC);


-- MedAxis: Medical documents and patient records
-- Do not add BEGIN/COMMIT: the existing migration runner handles transactions.

CREATE TABLE IF NOT EXISTS medical_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),

    document_code VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    category VARCHAR(60) NOT NULL,
    description TEXT,

    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    storage_path TEXT NOT NULL,
    mime_type VARCHAR(150) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0),

    document_date DATE,
    uploaded_by BIGINT REFERENCES users(id),

    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_medical_document_code
        UNIQUE (hospital_id, document_code)
);

CREATE INDEX IF NOT EXISTS idx_medical_documents_patient
    ON medical_documents (hospital_id, patient_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_medical_documents_category
    ON medical_documents (hospital_id, category);

CREATE INDEX IF NOT EXISTS idx_medical_documents_active
    ON medical_documents (hospital_id, is_archived, created_at DESC);

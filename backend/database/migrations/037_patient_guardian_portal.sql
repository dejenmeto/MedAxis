-- Patient and guardian access links.
-- The existing migration runner manages BEGIN / COMMIT.

CREATE TABLE IF NOT EXISTS patient_portal_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    portal_user_id BIGINT NOT NULL REFERENCES users(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    relationship VARCHAR(20) NOT NULL
        CHECK (relationship IN ('self', 'guardian')),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'revoked')),
    access_notes TEXT,
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, portal_user_id, patient_id)
);

CREATE INDEX IF NOT EXISTS idx_patient_portal_user
    ON patient_portal_access (hospital_id, portal_user_id, status);

CREATE INDEX IF NOT EXISTS idx_patient_portal_patient
    ON patient_portal_access (hospital_id, patient_id, status);
